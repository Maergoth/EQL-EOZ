import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import { mountFeatureVisibility } from '../app/feature-visibility.js';
import { FEATURE_CATALOG } from '../app/feature-registry.js';

const dom = new JSDOM('<main data-feature-ui="map"><section data-feature-ui="combat" hidden><input value="kept" disabled></section><button data-feature-ui="map npcIntel">Route</button><div data-feature-ui="unknown">Unknown</div><div data-feature-ui="">Empty</div></main>');
const { document, MutationObserver } = dom.window;
const root = document.querySelector('main');
const section = root.querySelector('section');
const route = root.querySelector('button');
const hidden = node => node.hasAttribute('data-feature-ui-hidden');
const next = () => new Promise(resolve => setTimeout(resolve, 0));
const view = mountFeatureVisibility({ root, features:{map:false}, MutationObserver });
assert(hidden(root), 'The root itself is projected');
assert(hidden(route));
assert(hidden(root.querySelector('[data-feature-ui="unknown"]')), 'Unknown identities fail closed');
assert(hidden(root.querySelector('[data-feature-ui=""]')), 'Empty identities fail closed');
assert.equal(hidden(section), false);
assert.equal(section.hidden, true);
view.setFeatures({npcIntel:false,combat:false});
assert.equal(hidden(root), false);
assert(hidden(route), 'Every space-separated requirement must be available');
assert(hidden(section));
view.setFeatures({});
assert.equal(hidden(route), false);
assert.equal(hidden(section), false);
assert.equal(section.hidden, true, 'Availability cannot reveal a component-hidden section');
assert.equal(section.querySelector('input').value, 'kept');
assert.equal(section.querySelector('input').disabled, true);
view.setFeatures({screenReading:false});
const dynamic = document.createElement('button');
dynamic.setAttribute('data-feature-ui', 'screenReading');
root.append(dynamic);
await next();
assert(hidden(dynamic), 'Dynamically mounted controls use the current feature map');
dynamic.setAttribute('data-feature-ui', 'character');
await next();
assert.equal(hidden(dynamic), false, 'Changing ownership reprojects without disturbing component state');
dynamic.setAttribute('data-feature-ui', 'screenReading');
await next();
assert(hidden(dynamic));
dynamic.removeAttribute('data-feature-ui');
await next();
assert.equal(hidden(dynamic), false, 'A reused core action drops only its previous feature projection');
view.dispose();
dynamic.setAttribute('data-feature-ui', 'screenReading');
await next();
assert.equal(hidden(dynamic), false, 'Disposed projection stops observing');
view.setFeatures({character:false});
assert.equal(hidden(dynamic), false);

const mainCss = await readFile(new URL('../app/styles.css', import.meta.url), 'utf8');
assert.match(mainCss, /\[data-feature-ui-hidden\][^{]*\{display:none!important\}/, 'Author layout rules cannot reveal disabled controls');
const mainHtml = new JSDOM(await readFile(new URL('../app/index.html', import.meta.url), 'utf8'));
for (const feature of FEATURE_CATALOG) for (const view of feature.views) for (const attribute of ['data-view','data-view-panel']) {
    const node = mainHtml.window.document.querySelector(`[${attribute}="${view}"]`);
    assert(node, `The ${view} view has a ${attribute} surface`);
    assert(node.getAttribute('data-feature-ui')?.split(/\s+/).includes(feature.id), `${view} entry points declare their feature ownership`);
    assert(hidden(node), 'Optional views remain hidden until initial availability has loaded');
}
mainHtml.window.close();
dom.window.close();
console.log('Feature visibility covers static/dynamic owners, AND requirements, unknown identities and component-state preservation.');
