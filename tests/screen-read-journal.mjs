import assert from 'node:assert/strict';
import {mkdtemp,rm,readdir,appendFile,writeFile,readFile,utimes} from 'node:fs/promises';
import {tmpdir} from 'node:os';import {join} from 'node:path';import {createRequire} from 'node:module';
const {ScreenReadJournal}=createRequire(import.meta.url)('../desktop/screen-read-journal.cjs');
const root=await mkdtemp(join(tmpdir(),'eoz-journal-test-'));
const observation=id=>({id,kind:'ocr',subject:{kind:'item',name:'Synthetic Blade'},fields:[{key:'ac',raw:'AC 12',value:12}],evidence:{text:'Synthetic text',imageId:null}});
try{
    let journal=new ScreenReadJournal({root,segmentBytes:400,maxBytes:2000});
    const records=await Promise.all(Array.from({length:6},(_,i)=>journal.append(observation(`synthetic-${i}`))));
    assert.deepEqual(records.map(record=>record.sequence),[1,2,3,4,5,6]);
    let history=await journal.read({afterSequence:2,limit:2});assert.deepEqual(history.records.map(record=>record.sequence),[3,4]);
    assert.equal(history.lastSequence,6);await journal.close();
    journal=new ScreenReadJournal({root,segmentBytes:400,maxBytes:2000});await journal.initialize();
    assert.equal((await journal.append(observation('restart'))).sequence,7,'cursor survives restart and rotation');
    const files=(await readdir(root)).filter(name=>name.endsWith('.ndjson'));
    await appendFile(join(root,files.at(-1)),'{"truncated":');
    history=await journal.read();assert.equal(history.records.some(record=>record.truncated),false);
    await appendFile(join(root,files[0]),'bad-json\n');
    history=await journal.read();assert.equal(history.historyGap,true);assert.ok(history.warnings.length);
    await assert.rejects(journal.append({...observation('oversize'),evidence:{text:'x'.repeat(140000)}}),/limit/);
    await assert.rejects(journal.read({afterSequence:-1}),/cursor/);
    await journal.clear();assert.equal((await journal.read()).records.length,0);
    assert.equal((await journal.append(observation('after-clear'))).sequence,8,'clear never rewinds durable sequence');
    await journal.close();await assert.rejects(journal.append(observation('closed')),/closed/);
    const state=JSON.parse(await readFile(join(root,'sequence.json'),'utf8'));assert.equal(state.sequence,8);
    const full=new ScreenReadJournal({root:join(root,'bounded'),maxQueuedBytes:300});
    await assert.rejects(full.append({...observation('queued'),extra:'x'.repeat(400)}),/busy/);await full.close();
    const timed=new ScreenReadJournal({root:join(root,'retention'),retentionMs:1000,now:()=>Date.now()});
    await timed.append(observation('old'));await timed.close();
    const oldFiles=(await readdir(join(root,'retention'))).filter(name=>name.endsWith('.ndjson'));
    for(const name of oldFiles)await utimes(join(root,'retention',name),new Date(0),new Date(0));
    const fresh=new ScreenReadJournal({root:join(root,'retention'),retentionMs:1000});await fresh.initialize();
    assert.equal((await fresh.read()).records.length,0,'expired raw history is pruned after its cursor is recovered');
    assert.equal((await fresh.append(observation('new'))).sequence,2);await fresh.close();
    const invalid=new ScreenReadJournal({root:join(root,'unsafe')});await invalid.initialize();
    await writeFile(join(root,'unsafe','screen-read-20261022-0000000000000000.ndjson'),'x'.repeat(5*1024*1024));
    await assert.rejects(invalid.read(),/size/);await invalid.close();
}finally{await rm(root,{recursive:true,force:true});}
console.log('Private screen-read journal: serialization, replay, crash tails, corruption, retention, bounded queues and durable cursors passed.');
