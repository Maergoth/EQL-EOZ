import assert from 'node:assert/strict';
import {CONTRIBUTION_CLASSES,CONTRIBUTION_SLOTS,normalizeContributionChoices as normalize,toggleContributionChoice as toggle,contributionChoicePickerMarkup as markup,readContributionChoicePicker as read,contributionChoicePlacement as placement} from '../app/contribution-choice-picker.js';

assert.equal(CONTRIBUTION_CLASSES.length,16);
assert.deepEqual(normalize('classes',['WAR','war','Cleric','Shadow Knight']).value,['WAR','CLR','SHD']);
assert.deepEqual(normalize('classes','Class: warrior / cleric; shadowknight, Beastlord').value,['WAR','CLR','SHD','BST']);
assert.deepEqual(normalize('classes','all').value,['ALL']);
assert.deepEqual(normalize('classes','none').value,['NONE']);
assert.deepEqual(normalize('classes',[]).value,[],'An optional blank is not an explicit no-class restriction.');
assert.deepEqual(normalize('classes',CONTRIBUTION_CLASSES.map(choice=>choice.value)).value,['ALL']);
const excluded=normalize('classes','ALL except CLR PAL Shadow Knight');
assert.equal(excluded.value.length,13);for(const code of ['CLR','PAL','SHD'])assert(!excluded.value.includes(code));
assert.deepEqual(excluded.unrecognized,[]);
assert.deepEqual(normalize('classes',['ALL except','CLR','PAL']).value,CONTRIBUTION_CLASSES.map(choice=>choice.value).filter(code=>!['CLR','PAL'].includes(code)));
assert.deepEqual(normalize('classes','WAR PLD <script>').unrecognized,['PLD','<script>'],'A mistyped code must not become a different allowed class.');
assert.deepEqual(normalize('slots','Slots: Primary / Secondary, Fingers, Ears, Wrist, Ranged, Power Source, shoulders').value,['EAR','SHOULDERS','WRIST','RANGE','PRIMARY','SECONDARY','FINGER','POWER SOURCE']);
assert.deepEqual(normalize('slots',['Any slot','charm','PowerSource']).value,['CHARM','POWER SOURCE','ANY']);
assert.deepEqual(normalize('slots','Primary banana').unrecognized,['banana']);
assert.equal(new Set(CONTRIBUTION_SLOTS.map(choice=>choice.value)).size,CONTRIBUTION_SLOTS.length);

assert.deepEqual(toggle('classes',[],'ALL'),['ALL']);
assert.deepEqual(toggle('classes',['ALL'],'ALL'),[]);
assert.deepEqual(toggle('classes',['ALL'],'NONE'),['NONE']);
assert.deepEqual(toggle('classes',['NONE'],'ROG'),['ROG']);
assert.deepEqual(toggle('classes',['NONE'],'NONE'),[]);
assert.equal(toggle('classes',['ALL'],'CLR').length,15);
assert(!toggle('classes',['ALL'],'CLR').includes('CLR'));
assert.deepEqual(toggle('classes',toggle('classes',['ALL'],'CLR'),'CLR'),['ALL']);
assert.deepEqual(toggle('slots',['PRIMARY'],'SECONDARY'),['PRIMARY','SECONDARY']);
assert.deepEqual(toggle('slots',['PRIMARY','SECONDARY'],'PRIMARY'),['SECONDARY']);
assert.deepEqual(toggle('slots',['PRIMARY'],'BOGUS'),['PRIMARY']);

const html=markup('classes',['ROG','<unknown>']);
assert(html.includes('aria-multiselectable="true"'));
assert(html.includes('aria-haspopup="listbox"'));
assert.equal((html.match(/role="option"/g)||[]).length,18);
assert(!html.includes('type="checkbox"'));
assert(html.includes('&lt;unknown&gt;'));assert(!html.includes('<unknown>'));
assert(html.includes('data-choice-option="ROG" role="option" tabindex="-1" aria-selected="true"'));
const original='Class: ALL except CLR badtoken';
const picker={dataset:{choicePicker:'classes',choiceOriginal:JSON.stringify(original)},querySelector:()=>({value:'ROG, WIZ'})};
assert.equal(read(picker),original,'Opening or saving another field must preserve legacy values until the selection is edited.');
picker.dataset.choiceEdited='true';assert.deepEqual(read(picker),['ROG','WIZ']);
assert.throws(()=>normalize('races','ALL'),/Unknown/);
assert.throws(()=>markup('races',[]),/Unknown/);
assert.deepEqual(placement({top:700,bottom:740},{top:0,bottom:800},290),{up:true,room:290},'A dropdown near the bottom opens above the field.');
assert.deepEqual(placement({top:20,bottom:60},{top:0,bottom:800},290),{up:false,room:290});
assert.deepEqual(placement({top:240,bottom:280},{top:200,bottom:350},290),{up:false,room:66},'A nested scroll panel limits the menu to its available room.');
assert.deepEqual(placement({top:330,bottom:370},{top:200,bottom:400},290),{up:true,room:126});
console.log('Contribution dropdown choices: canonical vocabulary, multiple selections, legacy preservation and safe markup pass.');
