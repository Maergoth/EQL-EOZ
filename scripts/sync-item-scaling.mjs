// The wiki owns these files. Synchronize reviewed source, never a hand-maintained
// formula fork. Runtime refresh downloads validated rule data, never JavaScript.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'app/vendor');
const paths = ['item-scaling-core.js', 'item-scaling-rules.json', 'item-scaling-core.LICENSE'];
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const arg = name => process.argv.includes(name) ? process.argv[process.argv.indexOf(name) + 1] : '';
const generated = rules => `// Generated by scripts/sync-item-scaling.mjs. Edit the wiki-owned JSON source.\nexport default ${JSON.stringify(rules, null, 2)};\n`;

if (process.argv.includes('--check')) {
    const record = JSON.parse(await readFile(resolve(target, 'item-scaling-source.json'), 'utf8'));
    if (record.repository !== 'Maergoth/EQLWiki' || !/^[a-f0-9]{40}$/.test(record.commit)) throw Error('Invalid shared formula source receipt.');
    for (const name of paths) {
        if (sha(await readFile(resolve(target, name))) !== record.sha256[name]) throw Error(`Shared ${name} changed: synchronize it from the wiki source.`);
    }
    const rules = JSON.parse(await readFile(resolve(target, 'item-scaling-rules.json'), 'utf8'));
    if (await readFile(resolve(target, 'item-scaling-rules.js'), 'utf8') !== generated(rules)) throw Error('Generated shared item rules are stale.');
    await import('../app/vendor/item-scaling-core.js');
    if (!globalThis.EQLItemScalingCore.validateRules(rules)) throw Error('Unsupported bundled item rules.');
    console.log(`Shared item formulas verified: wiki ${record.commit.slice(0, 12)}, rules ${rules.revision}.`);
} else {
    const commit = arg('--ref');
    if (!/^[a-f0-9]{40}$/.test(commit)) throw Error('Pass --ref <reviewed full wiki commit SHA>. Optionally add --source-root <wiki checkout>.');
    const sourceRoot = arg('--source-root');
    const files = {};
    for (const name of paths) {
        if (sourceRoot) {
            const working = await readFile(resolve(sourceRoot, 'extensions/ItemLevelSlider', name));
            const committed=execFileSync('git',['-c',`safe.directory=${resolve(sourceRoot).replaceAll('\\','/')}`,'-C',sourceRoot,'show',`${commit}:extensions/ItemLevelSlider/${name}`]);
            if (working.toString('utf8').replaceAll('\r\n','\n')!==committed.toString('utf8').replaceAll('\r\n','\n')) throw Error(`Local ${name} is not the reviewed wiki commit; commit or restore it before synchronization.`);
            files[name]=committed;
        }
        else {
            const url = `https://raw.githubusercontent.com/Maergoth/EQLWiki/${commit}/extensions/ItemLevelSlider/${name}`;
            const response = await fetch(url, { signal:AbortSignal.timeout(10000), redirect:'error' });
            if (!response.ok) throw Error(`Cannot synchronize ${name}: HTTP ${response.status}`);
            const bytes = Buffer.from(await response.arrayBuffer());
            if (bytes.length > 64 * 1024) throw Error('Shared formula source is unexpectedly large.');
            files[name] = bytes;
        }
    }
    const rules = JSON.parse(files['item-scaling-rules.json']);
    await mkdir(target, { recursive:true });
    for (const name of paths) await writeFile(resolve(target, name), files[name]);
    await writeFile(resolve(target, 'item-scaling-rules.js'), generated(rules));
    const record = { repository:'Maergoth/EQLWiki', commit, directory:'extensions/ItemLevelSlider',
        sha256:Object.fromEntries(paths.map(name => [name, sha(files[name])])) };
    await writeFile(resolve(target, 'item-scaling-source.json'), `${JSON.stringify(record, null, 2)}\n`);
    console.log(`Synchronized shared item formulas from wiki ${commit}. Run --check and the parity tests before committing.`);
}
