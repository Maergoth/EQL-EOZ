// Release tooling only: take one wiki source snapshot for both app packages.
// Installed applications use their bundled formulas and never run this script.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'app/vendor');
export const SCALING_SOURCE_FILES = Object.freeze(['item-scaling-core.js', 'item-scaling-rules.json', 'item-scaling-core.LICENSE']);
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const generated = rules => `// Generated by scripts/sync-item-scaling.mjs. Edit the wiki-owned JSON source.\nexport default ${JSON.stringify(rules, null, 2)};\n`;

async function sourceBytes(url, fetchImpl) {
    const response=await fetchImpl(url,{signal:AbortSignal.timeout(10000),redirect:'error',headers:{Accept:'application/vnd.github+json'}});
    if (!response.ok) throw Error(`Cannot read shared formula source: HTTP ${response.status}`);
    const maximum=64*1024;
    if (Number(response.headers.get('content-length')||0)>maximum) {void response.body?.cancel().catch(()=>{});throw Error('Shared formula source is unexpectedly large.');}
    const reader=response.body?.getReader();
    if (!reader) throw Error('Shared formula source is empty.');
    const chunks=[];let size=0;
    try {
        while (true) {
            const {done,value}=await reader.read();if (done) break;
            size+=value.byteLength;
            if (size>maximum) {void reader.cancel().catch(()=>{});throw Error('Shared formula source is unexpectedly large.');}
            chunks.push(Buffer.from(value));
        }
    } finally {reader.releaseLock();}
    return Buffer.concat(chunks,size);
}

export async function loadItemScalingSnapshot({ref,sourceRoot,fetchImpl=fetch}={}) {
    let commit=ref;
    if (!commit) {
        // Resolve main once. All later reads use this commit, even if another
        // wiki change deploys while the two platform builds are running.
        const response=JSON.parse(await sourceBytes('https://api.github.com/repos/Maergoth/EQLWiki/git/ref/heads/main',fetchImpl));
        if (response.object?.type!=='commit') throw Error('Wiki main does not identify a commit.');
        commit=response.object.sha;
    }
    if (!/^[a-f0-9]{40}$/.test(commit||'')) throw Error('Shared formulas need an exact full wiki commit SHA.');
    const files={};
    for (const name of SCALING_SOURCE_FILES) {
        if (sourceRoot) {
            const working=await readFile(resolve(sourceRoot,'extensions/ItemLevelSlider',name));
            const committed=execFileSync('git',['-c',`safe.directory=${resolve(sourceRoot).replaceAll('\\','/')}`,'-C',sourceRoot,'show',`${commit}:extensions/ItemLevelSlider/${name}`]);
            if (working.toString('utf8').replaceAll('\r\n','\n')!==committed.toString('utf8').replaceAll('\r\n','\n')) throw Error(`Local ${name} is not the reviewed wiki commit; commit or restore it before synchronization.`);
            files[name]=committed;
        } else files[name]=await sourceBytes(`https://raw.githubusercontent.com/Maergoth/EQLWiki/${commit}/extensions/ItemLevelSlider/${name}`,fetchImpl);
    }
    const rules=JSON.parse(files['item-scaling-rules.json']);
    return {files,rules,record:{repository:'Maergoth/EQLWiki',commit,directory:'extensions/ItemLevelSlider',
        sha256:Object.fromEntries(SCALING_SOURCE_FILES.map(name=>[name,sha(files[name])]))}};
}

export async function writeItemScalingSnapshot(snapshot,directory=target) {
    await mkdir(directory,{recursive:true});
    for (const name of SCALING_SOURCE_FILES) await writeFile(resolve(directory,name),snapshot.files[name]);
    await writeFile(resolve(directory,'item-scaling-rules.js'),generated(snapshot.rules));
    await writeFile(resolve(directory,'item-scaling-source.json'),`${JSON.stringify(snapshot.record,null,2)}\n`);
}

export async function checkItemScalingSnapshot(directory=target) {
    const record=JSON.parse(await readFile(resolve(directory,'item-scaling-source.json'),'utf8'));
    if (record.repository!=='Maergoth/EQLWiki'||!/^[a-f0-9]{40}$/.test(record.commit)) throw Error('Invalid shared formula source receipt.');
    for (const name of SCALING_SOURCE_FILES) if (sha(await readFile(resolve(directory,name)))!==record.sha256[name]) throw Error(`Shared ${name} changed: synchronize it from the wiki source.`);
    const rules=JSON.parse(await readFile(resolve(directory,'item-scaling-rules.json'),'utf8'));
    if (await readFile(resolve(directory,'item-scaling-rules.js'),'utf8')!==generated(rules)) throw Error('Generated shared item rules are stale.');
    return {record,rules};
}

if (process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
    const arg=name=>process.argv.includes(name)?process.argv[process.argv.indexOf(name)+1]:'';
    if (!process.argv.includes('--check')) {
        const ref=arg('--ref');
        if (!ref&&!process.argv.includes('--from-wiki-main')) throw Error('Pass --ref <reviewed wiki commit>, or --from-wiki-main during release preparation.');
        await writeItemScalingSnapshot(await loadItemScalingSnapshot({ref,sourceRoot:arg('--source-root')}));
    }
    const {record,rules}=await checkItemScalingSnapshot();
    await import('../app/vendor/item-scaling-core.js');
    if (!globalThis.EQLItemScalingCore.validateRules(rules)) throw Error('Unsupported bundled item rules.');
    console.log(`Shared item formulas verified: wiki ${record.commit.slice(0,12)}, rules ${rules.revision}.`);
}
